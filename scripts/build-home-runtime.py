#!/usr/bin/env python3
"""Bundle the existing homepage sources without a package installation."""
from pathlib import Path
import hashlib
import re

ROOT = Path(__file__).resolve().parent.parent
JS = ['js/page-ready.js', 'app.js', 'js/media-loader.js', 'animations.js', 'js/bloom-scroll-video.js', 'js/bloom-glass.js', 'js/bloom-flower-video.js']
CSS = ['styles.css', 'css/bloom-parallax.css', 'css/approach-imagery.css',
       'css/journal-feature.css', 'css/footer-bloom.css', 'css/home-content.css', 'css/inner-pages.css', 'css/bloom-glass.css']

def bundle(paths, kind):
    parts = ['/* Generated by scripts/build-home-runtime.py. Edit the source files. */\n']
    for relative in paths:
        content = (ROOT / relative).read_text()
        if relative == 'styles.css':
            content = content.replace("url('assets/", "url('../assets/").replace('url("assets/', 'url("../assets/')
        parts.append(f'\n/* Source: {relative} */\n{content}\n')
        if kind == 'js':
            parts.append(';\n')
    content = ''.join(parts)
    digest = hashlib.sha256(content.encode()).hexdigest()[:12]
    folder = 'js' if kind == 'js' else 'css'
    target = f'{folder}/home-runtime-{digest}.{kind}'
    (ROOT / target).write_text(content)
    for old in (ROOT / folder).glob(f'home-runtime-*.{kind}'):
        if old != ROOT / target and old.read_text().startswith('/* Generated by scripts/build-home-runtime.py.'):
            old.unlink()
    return target

script = bundle(JS, 'js')
style = bundle(CSS, 'css')
html_path = ROOT / 'index.html'
html = html_path.read_text()
block = f'''  <!-- HOME_ASSETS_BEGIN -->
  <link rel="stylesheet" href="{style}" onerror="window.dispatchEvent(new Event('bloom:startup-error'))">
  <link rel="preload" href="{script}" as="script">
  <script src="{script}" defer onerror="window.dispatchEvent(new Event('bloom:startup-error'))"></script>
  <!-- HOME_ASSETS_END -->'''
if '<!-- HOME_ASSETS_BEGIN -->' in html:
    html = re.sub(r'  <!-- HOME_ASSETS_BEGIN -->.*?  <!-- HOME_ASSETS_END -->', lambda _: block, html, flags=re.S)
else:
    html = re.sub(r'  <link rel="stylesheet".*?  <script src="js/bloom-scroll-video\.js[^\n]*</script>', lambda _: block, html, count=1, flags=re.S)
html_path.write_text(html)
print(f'Homepage assets: {script}, {style}')
